    async def ejecutar_ciclo_rastreo(self):
        """
        Rastrea, sanitiza, valida de pre-vuelo y actualiza el archivo JSON de manera atómica.
        """
        logger.info("Escaneando el enjambre de feeds comerciales globales...")
        
        productos_sanitizados = []
        
        # Procesamos en paralelo la lista de candidatos
        for i, item in enumerate(PRODUCTOS_TOTALES):
            product_id = item["id"]
            
            # 1. Comprobación de Pre-Vuelo Asíncrona
            enlace_original = item["url_base"]
            es_valido = await self.ping_async_prevuelo(enlace_original)
            
            if not es_valido:
                logger.warning(f"Pre-vuelo Fallido: Enlace '{enlace_original}' caído. Purgando de inmediato.")
                continue  # Salta la inyección si falla el ping
                
            # 2. Ensamblar enlace limpio con tracking inyectado
            enlace_afiliado = self.deconstruir_y_ensamblar_enlace(enlace_original, item["platform"])
            
            # 3. Formatear la estructura relacional de precios
            original = item["original_price"]
            current = item["current_price"]
            descuento = int(((original - current) / original) * 100) if original > 0 else 0
            
            # Maquetar temporalmente sin relacionados para evitar autoreferencia circular
            producto = {
                "id": product_id,
                "platform": item["platform"],
                "category": item["category"],
                "subcategory": item.get("subcategory", "Otros"),
                "title": item["title"],
                "description": item["description"],
                "original_price": original,
                "current_price": current,
                "rating": item["rating"],
                "clean_affiliate_link": enlace_afiliado,
                "url_base": enlace_original,
                "image": item["image"],
                "images": item.get("images", []),
                "pricing": {
                    "original_price": original,
                    "current_price": current,
                    "discount_percentage": descuento,
                    "currency": "MXN",
                    "display_discount_in_red": True
                },
                "related_products": []
            }
            productos_sanitizados.append(producto)

        # 4. Inyección del enlazado de retención cruzada (Quienes compraron esto también...)
        for prod in productos_sanitizados:
            prod["related_products"] = self.simular_articulos_relacionados(
                productos_sanitizados, prod["id"]
            )

        # 5. Estructurar el payload final de catalog.json (versionado)
        catalog_payload = {
          "viamx_catalog_version": "2026.2.0",
          "last_updated": datetime.now().isoformat() + "Z",
          "tracking_metadata": {
            "global_amazon_tag": self.tracking_tag,
            "global_mercadolibre_utm": self.utm_campaign,
            "redirection_gateway": "https://viamx.pro/redirect"
          },
          "products": productos_sanitizados
        }

        # 6. Mapear a formato plano
        flat_payload = self.mapear_a_catalogo_plano(productos_sanitizados)

        # Escritura Atómica del catálogo versionado a la raíz de D:
        try:
            temp_path = CATALOG_PATH_ROOT + ".tmp"
            with open(temp_path, "w", encoding="utf-8") as f:
                json.dump(catalog_payload, f, indent=2, ensure_ascii=False)
            os.replace(temp_path, CATALOG_PATH_ROOT)
            logger.info(f"Catálogo raíz '{CATALOG_PATH_ROOT}' actualizado (Formato versionado).")
        except Exception as e:
            logger.error(f"Error crítico escribiendo el catálogo raíz: {e}")

        # Escritura de catálogos planos a todos los destinos configurados
        for path in FLAT_PATHS:
            try:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                temp_path = path + ".tmp"
                with open(temp_path, "w", encoding="utf-8") as f:
                    json.dump(flat_payload, f, indent=2, ensure_ascii=False)
                os.replace(temp_path, path)
                logger.info(f"Destino plano actualizado: '{path}'")
            except Exception as e:
                logger.error(f"Error escribiendo catálogo plano a {path}: {e}")

    async def loop_demonio_infinito(self):
        """
        Ejecuta de manera infinita el rastreo con intervalos fijos en segundo plano.
        """
        logger.info(f"Demonio activado. Intervalo de refresco: {self.check_interval_sec} segundos.")
        while True:
            try:
                await self.ejecutar_ciclo_rastreo()
            except Exception as e:
                logger.error(f"Excepción en el ciclo del bucle: {e}")
            await asyncio.sleep(self.check_interval_sec)

