    def _sync_ping_prevuelo(self, url: str) -> bool:
        import urllib.request
        import urllib.parse
        headers = {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
        }
        try:
            req = urllib.request.Request(url, headers=headers, method='HEAD')
            with urllib.request.urlopen(req, timeout=5) as response:
                final_url = response.url
                if "tanga" in final_url.lower() or "lenceria" in final_url.lower() or "ropa-interior" in final_url.lower():
                    logger.warning(f"HEAD: Redirección a lencería bloqueada: {url} -> {final_url}")
                    return False
                if "buscar" in final_url.lower() or "search" in final_url.lower():
                    logger.warning(f"HEAD: Redirección a buscador bloqueada: {url} -> {final_url}")
                    return False
                return response.status == 200
        except Exception:
            try:
                req = urllib.request.Request(url, headers=headers, method='GET')
                with urllib.request.urlopen(req, timeout=5) as response:
                    final_url = response.url
                    if "tanga" in final_url.lower() or "lenceria" in final_url.lower() or "ropa-interior" in final_url.lower():
                        logger.warning(f"GET: Redirección a lencería bloqueada: {url} -> {final_url}")
                        return False
                    if "buscar" in final_url.lower() or "search" in final_url.lower():
                        logger.warning(f"GET: Redirección a buscador bloqueada: {url} -> {final_url}")
                        return False
                    return response.status == 200
            except Exception as e:
                logger.error(f"Error comprobando enlace {url}: {e}")
                return False

    async def ping_async_prevuelo(self, url: str) -> bool:
        """
        Ejecuta una petición HEAD/GET de pre-vuelo real en un hilo secundario
        para comprobar que el enlace no esté roto ni redirija incorrectamente.
        """
        import asyncio
        loop = asyncio.get_event_loop()
        return await loop.run_in_executor(None, self._sync_ping_prevuelo, url)

    def deconstruir_y_ensamblar_enlace(self, url_base: str, platform: str) -> str:
        """
        Construye una URL de afiliación directa, limpia y libre de ganchos de
        spam, inyectando de golpe las claves de atribución transnacional.
        """
        parsed = urllib.parse.urlparse(url_base)
        query_params = urllib.parse.parse_qs(parsed.query)
        
        # Limpieza forense de parámetros espurios de tracking ajenos
        for key in list(query_params.keys()):
            if key not in ["id", "product_id", "goods_id", "ASIN", "k", "q", "s", "palabra", "original"]:
                query_params.pop(key, None)

        # Inyectar las variables de producción 2026 unificadas
        if "amazon" in platform:
            query_params["tag"] = [self.tracking_tag]
            query_params["linkCode"] = ["ogi"]
        elif "mercadolibre" in platform:
            query_params["utm_source"] = ["affiliate"]
            query_params["utm_medium"] = [self.utm_campaign]
        else:
            query_params["click_id"] = [f"viamx_s2s_{int(datetime.now().timestamp())}"]

        new_query = urllib.parse.urlencode(query_params, doseq=True)
        return urllib.parse.urlunparse((
            parsed.scheme,
            parsed.netloc,
            parsed.path,
            parsed.params,
            new_query,
            parsed.fragment
        ))

    def simular_articulos_relacionados(self, catalog_products: List[Dict], current_id: str) -> List[Dict]:
        """
        Construye el bloque relacional dinámico con 4 productos para
        satisfacer el motor de retención 'Quienes compraron esto también adquirieron...'
        """
        relacionados = []
        otros_productos = [p for p in catalog_products if p["id"] != current_id]
        
        # Seleccionar hasta 4 productos aleatorios para rellenar el slot de retención
        items_muestra = random.sample(otros_productos, min(len(otros_productos), 4))
        for item in items_muestra:
            relacionados.append({
                "product_id": item["id"],
                "title": item["title"],
                "current_price": item["current_price"],
                "affiliate_link": item["url_base"]
            })
        return relacionados

