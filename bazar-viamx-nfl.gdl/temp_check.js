      const progressBar = document.getElementById('progress-bar');
      if (progressBar) progressBar.style.width = `${progressPercent}%`;

      const progressTextUnder = document.getElementById('progress-text-under');
      if (progressTextUnder) progressTextUnder.innerText = `Progreso: ${progressPercent}% para cubrir costos de mantenimiento`;

      const progressPercentageLabel = document.getElementById('progress-percentage-label');
      if (progressPercentageLabel) progressPercentageLabel.innerText = `$${commissions.toFixed(2)} / $${targetAlojamiento.toFixed(2)} MXN`;
