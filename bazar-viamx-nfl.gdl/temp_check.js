    // ENRUTADOR DINÁMICO (Habilitador del botón "Atrás" del navegador)
    function handleRouting() {
      const hash = window.location.hash.replace('#', '');
      
      const catalog = document.getElementById('catalogSection');
      const placeholder = document.getElementById('placeholderSection');
      const detail = document.getElementById('detailSection');
      const sedes = document.getElementById('sedesSection');

      if (!hash) {
        if (sedes) sedes.classList.add('hidden');
        changePage(activePage, false);
        return;
      }

      if (hash === 'sedes') {
        showSedesPage(false);
        return;
      }

      if (hash.startsWith('page-')) {
        const pageNum = parseInt(hash.replace('page-', ''));
        if (pageNum >= 1) {
          if (sedes) sedes.classList.add('hidden');
          changePage(pageNum, false);
          return;
        }
      }

      const product = productsDB.find(p => p.slug === hash);
      if (product) {
        if (sedes) sedes.classList.add('hidden');
        showProductDetail(product.id, false);
      } else {
        if (sedes) sedes.classList.add('hidden');
        backToCatalog(false);
      }
    }

    // MANEJADORES DE PAGINACIÓN
    function changePage(pageNum, updateHash = true) {
      activePage = pageNum;
      
      const catalog = document.getElementById('catalogSection');
      const placeholder = document.getElementById('placeholderSection');
      const detail = document.getElementById('detailSection');
      const sedes = document.getElementById('sedesSection');

      catalog.classList.remove('hidden');
      placeholder.classList.add('hidden');
      detail.classList.add('hidden');
      if (sedes) sedes.classList.add('hidden');
      
      filterProducts();

      if (updateHash) {
        if (pageNum === 1) {
          history.pushState(null, '', '#');
        } else {
          history.pushState(null, '', '#page-' + pageNum);
        }
      }

      window.scrollTo({ top: 0, behavior: 'smooth' });
    }

