    // Filtro síncrono general
    function filterProducts() {
      const query = document.getElementById('search-input').value.toLowerCase().trim();
      const category = document.getElementById('category-select').value;
      const priceLimit = parseFloat(document.getElementById('filter-price-range').value);
      
      const filterAmazon = document.getElementById('filter-src-amazon').checked;
      const filterMeli = document.getElementById('filter-src-meli').checked;
      const filterAlibaba = document.getElementById('filter-src-alibaba').checked;
      const filterAliExpress = document.getElementById('filter-src-aliexpress').checked;
      const filterMercadoPago = document.getElementById('filter-src-mercadopago').checked;
      const filterTemu = document.getElementById('filter-src-temu').checked;
      const filterSears = document.getElementById('filter-src-sears').checked;
      const filterLiverpool = document.getElementById('filter-src-liverpool').checked;
      const filterPalacio = document.getElementById('filter-src-palacio').checked;
      const filterAurrera = document.getElementById('filter-src-aurrera').checked;
      const filterLaComer = document.getElementById('filter-src-lacomer').checked;

      const cityRadios = document.getElementsByName('city-filter');
      let selectedCity = 'all';
      cityRadios.forEach(radio => {
        if (radio.checked) selectedCity = radio.value;
      });

      let filtered = productsDB.filter(product => {
        const matchesQuery = !query || 
          product.title.toLowerCase().includes(query) || 
          (product.physicalDesc && product.physicalDesc.toLowerCase().includes(query)) ||
          product.subcategory.toLowerCase().includes(query);

        const matchesCategory = (category === 'all' || product.category === category);
        const matchesSubcategory = !activeFilterSubcategory || (product.subcategory === activeFilterSubcategory);
        const matchesPrice = product.price <= priceLimit;
        const matchesRating = product.rating >= selectedStarRating;
        const matchesCity = (selectedCity === 'all' || product.city === selectedCity || product.city === 'all');

        let matchesPlatform = false;
        if (product.source.includes("Amazon") && filterAmazon) matchesPlatform = true;
        else if (product.source.includes("Mercado Libre") && filterMeli) matchesPlatform = true;
        else if (product.source.includes("Alibaba") && filterAlibaba) matchesPlatform = true;
        else if (product.source.includes("AliExpress") && filterAliExpress) matchesPlatform = true;
        else if (product.source.includes("Mercado Pago") && filterMercadoPago) matchesPlatform = true;
        else if (product.source.includes("Temu") && filterTemu) matchesPlatform = true;
        else if (product.source.includes("Sears") && filterSears) matchesPlatform = true;
        else if (product.source.includes("Liverpool") && filterLiverpool) matchesPlatform = true;
        else if (product.source.includes("Palacio") && filterPalacio) matchesPlatform = true;
        else if (product.source.includes("Aurrera") && filterAurrera) matchesPlatform = true;
        else if (product.source.includes("La Comer") && filterLaComer) matchesPlatform = true;
        else if (!product.source) matchesPlatform = true;

        return matchesQuery && matchesCategory && matchesSubcategory && matchesPrice && matchesRating && matchesPlatform && matchesCity;
      });

      // Actualizar título de categoría arriba de la rejilla
      const gridCatTitle = document.getElementById('grid-category-title');
      if (gridCatTitle) {
        if (category !== 'all') {
          gridCatTitle.textContent = `Departamento: ${category}`;
          gridCatTitle.classList.remove('hidden');
        } else if (activeFilterSubcategory) {
          gridCatTitle.textContent = `Sección: ${subcategoryTranslations[activeFilterSubcategory] || activeFilterSubcategory}`;
          gridCatTitle.classList.remove('hidden');
        } else {
          gridCatTitle.classList.add('hidden');
        }
      }

      // Ordenar resultados
      const sortOption = document.getElementById('sort-select').value;
      if (sortOption === "price-asc") {
        filtered.sort((a, b) => a.price - b.price);
      } else if (sortOption === "price-desc") {
        filtered.sort((a, b) => b.price - a.price);
      } else if (sortOption === "popular") {
        filtered.sort((a, b) => b.ratingCount - a.ratingCount);
      } else if (sortOption === "newest") {
        filtered.sort((a, b) => b.id.localeCompare(a.id));
      } else if (sortOption === "rating") {
        filtered.sort((a, b) => b.rating - a.rating);
      } else {
        filtered.sort((a, b) => (b.rating * b.ratingCount) - (a.rating * a.ratingCount));
      }

      // Paginación dinámica real (30 productos por página)
      const productsPerPage = 30;
      const totalPages = Math.ceil(filtered.length / productsPerPage) || 1;
      
      if (activePage > totalPages) {
        activePage = totalPages;
      }
      
      const start = (activePage - 1) * productsPerPage;
      const end = start + productsPerPage;
      const pageProducts = filtered.slice(start, end);
      
      renderProductGrid(pageProducts);
      
      // Dibujar botones de paginación de forma dinámica
      const paginationChassis = document.getElementById('paginationChassis');
      if (paginationChassis) {
        paginationChassis.innerHTML = '';
        
        // Botón Anterior
        if (totalPages > 1) {
          const prevBtn = document.createElement('button');
          prevBtn.textContent = '«';
          prevBtn.onclick = () => {
            if (activePage > 1) changePage(activePage - 1);
          };
          prevBtn.className = "px-3 py-2 border border-gray-200 text-gray-600 rounded hover:border-champagne hover:text-champagne font-medium text-sm transition-all duration-150 cursor-pointer" + (activePage === 1 ? " opacity-50 cursor-not-allowed" : "");
          paginationChassis.appendChild(prevBtn);
        }

        // Páginas numéricas
        for (let i = 1; i <= totalPages; i++) {
          const btn = document.createElement('button');
          btn.textContent = i;
          btn.onclick = () => changePage(i);
          if (i === activePage) {
            btn.className = "px-4 py-2 bg-harrods text-champagne border border-champagne rounded font-bold text-sm transition-all duration-150 cursor-pointer";
          } else {
            btn.className = "px-4 py-2 border border-gray-200 text-gray-600 rounded hover:border-champagne hover:text-champagne font-medium text-sm transition-all duration-150 cursor-pointer";
          }
          paginationChassis.appendChild(btn);
        }

        // Botón Siguiente
        if (totalPages > 1) {
          const nextBtn = document.createElement('button');
          nextBtn.textContent = '»';
          nextBtn.onclick = () => {
            if (activePage < totalPages) changePage(activePage + 1);
          };
          nextBtn.className = "px-3 py-2 border border-gray-200 text-gray-600 rounded hover:border-champagne hover:text-champagne font-medium text-sm transition-all duration-150 cursor-pointer" + (activePage === totalPages ? " opacity-50 cursor-not-allowed" : "");
          paginationChassis.appendChild(nextBtn);
        }
      }
      
      const pageDesc = document.getElementById('pageDescription');
      if (pageDesc) {
        pageDesc.textContent = `Mostrando ${pageProducts.length} de ${filtered.length} artículos exclusivos (Página ${activePage} de ${totalPages})`;
      }
      
      // Actualizar contador
      const resultsCounter = document.getElementById('results-counter');
      if (resultsCounter) {
        resultsCounter.innerText = "Curaduría de Artículos Exclusivos";
      }
    }

